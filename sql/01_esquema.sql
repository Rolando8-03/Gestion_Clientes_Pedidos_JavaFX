-- Ejecutar conectado a gestion_uam. También permite preparar una base vacía sin abrir JavaFX.
BEGIN;

CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    correo VARCHAR(150) NOT NULL UNIQUE,
    CONSTRAINT ck_cliente_nombre CHECK (length(btrim(nombre)) > 0),
    CONSTRAINT ck_cliente_correo CHECK (length(btrim(correo)) > 0)
);

-- Refuerza la validación del servicio incluso ante escrituras simultáneas.
CREATE UNIQUE INDEX IF NOT EXISTS ux_clientes_correo_normalizado
    ON clientes (lower(btrim(correo)));

CREATE TABLE IF NOT EXISTS pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(150) NOT NULL,
    total NUMERIC(12, 2) NOT NULL,
    fecha DATE NOT NULL,
    cliente_id BIGINT NOT NULL,
    CONSTRAINT ck_pedido_descripcion CHECK (length(btrim(descripcion)) > 0),
    CONSTRAINT ck_pedido_total CHECK (total > 0),
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (cliente_id)
        REFERENCES clientes(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_pedidos_cliente ON pedidos (cliente_id);
COMMIT;
